#!/bin/sh
set -eu

template="/usr/share/nginx/html/assets/env.template.js"
target="/usr/share/nginx/html/assets/env.js"

if [ -f "$template" ]; then
  API_URL="${API_URL:-http://localhost:8080/api/v1}"
  KEYCLOAK_URL="${KEYCLOAK_URL:-http://127.0.0.1:8081}"
  KEYCLOAK_REALM="${KEYCLOAK_REALM:-asistencias-uco}"
  KEYCLOAK_CLIENT_ID="${KEYCLOAK_CLIENT_ID:-asistencias-uco-frontend}"
  USE_MOCKS="${USE_MOCKS:-false}"
  SECURITY_PROVIDER="${SECURITY_PROVIDER:-legacy}"
  SECURITY_BASELINE_URL="${SECURITY_BASELINE_URL:-http://localhost:18080}"
  SECURITY_BASELINE_APPLICATION_NAME="${SECURITY_BASELINE_APPLICATION_NAME:-AsistenciasUCO}"

  export API_URL KEYCLOAK_URL KEYCLOAK_REALM KEYCLOAK_CLIENT_ID USE_MOCKS SECURITY_PROVIDER SECURITY_BASELINE_URL SECURITY_BASELINE_APPLICATION_NAME
  envsubst '${API_URL} ${KEYCLOAK_URL} ${KEYCLOAK_REALM} ${KEYCLOAK_CLIENT_ID} ${USE_MOCKS} ${SECURITY_PROVIDER} ${SECURITY_BASELINE_URL} ${SECURITY_BASELINE_APPLICATION_NAME}' < "$template" > "$target"
fi
